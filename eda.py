# 6. Correlation Analysis
# ============================================================
def _correlation_analysis(df, output_dir):
    """Generate correlation heatmap for numerical/binary features."""
    print("\n--- Correlation Analysis ---")

    # Select numeric columns and encode binary categoricals for correlation
    df_corr = df.copy()
    df_corr['gender_encoded'] = df_corr['gender'].map({'Male': 0, 'Female': 1, 'Other': 2})
    df_corr['ever_married_encoded'] = df_corr['ever_married'].map({'No': 0, 'Yes': 1})
    df_corr['Residence_encoded'] = df_corr['Residence_type'].map({'Rural': 0, 'Urban': 1})

    corr_cols = ['age', 'hypertension', 'heart_disease', 'avg_glucose_level', 'bmi',
                 'gender_encoded', 'ever_married_encoded', 'Residence_encoded', 'stroke']

    corr_matrix = df_corr[corr_cols].corr()

    plt.figure(figsize=(12, 10))
    mask = np.triu(np.ones_like(corr_matrix, dtype=bool))
    sns.heatmap(
        corr_matrix, mask=mask, annot=True, fmt='.3f',
        cmap='RdBu_r', center=0, square=True,
        linewidths=0.5, cbar_kws={'shrink': 0.8}
    )
    plt.title('Correlation Heatmap', fontsize=15, fontweight='bold')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '07_correlation_heatmap.png'), bbox_inches='tight')
    plt.close()

    # Print top correlations with stroke
    stroke_corr = corr_matrix['stroke'].drop('stroke').abs().sort_values(ascending=False)
    print("\nCorrelation with stroke (absolute values):")
    for feat, corr in stroke_corr.items():
        print(f"  {feat}: {corr:.4f}")


