# 2. Target Analysis
# ============================================================
def _target_analysis(df, output_dir):
    """Analyze and visualize the target variable distribution."""
    print("\n--- Target Variable Analysis ---")

    stroke_counts = df['stroke'].value_counts()
    total = len(df)

    no_stroke = stroke_counts[0]
    stroke = stroke_counts[1]

    print(f"No Stroke (0): {no_stroke}  ({no_stroke/total*100:.2f}%)")
    print(f"Stroke (1):    {stroke}  ({stroke/total*100:.2f}%)")
    print(f"Imbalance Ratio: {no_stroke/stroke:.1f}:1")

    # Class imbalance bar chart + pie chart
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    colors = ['#4CAF50', '#F44336']

    # Count plot
    axes[0].bar(['No Stroke\n(0)', 'Stroke\n(1)'],
                [no_stroke, stroke], color=colors, edgecolor='black', linewidth=0.5)
    axes[0].set_title('Stroke Class Distribution (Counts)', fontsize=13, fontweight='bold')
    axes[0].set_ylabel('Count', fontsize=11)
    for i, v in enumerate([no_stroke, stroke]):
        axes[0].text(i, v + 50, str(v), ha='center', fontweight='bold', fontsize=12)

    # Percentage pie chart
    axes[1].pie([no_stroke, stroke],
                labels=['No Stroke', 'Stroke'],
                autopct='%1.1f%%',
                colors=colors,
                startangle=90,
                explode=(0, 0.1),
                textprops={'fontsize': 12})
    axes[1].set_title('Stroke Class Distribution (Percentage)', fontsize=13, fontweight='bold')

    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '01_target_distribution.png'), bbox_inches='tight')
    plt.close()


