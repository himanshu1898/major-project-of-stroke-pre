# 1. Dataset Information
# ============================================================
def _dataset_info(df):
    """Print comprehensive dataset information."""
    print("\n--- Dataset Information ---")
    print(f"Shape: {df.shape}")
    print(f"Rows:  {df.shape[0]}")
    print(f"Cols:  {df.shape[1]}")

    print(f"\n--- Data Types ---")
    print(df.dtypes)

    print(f"\n--- Missing Values ---")
    missing = df.isnull().sum()
    missing_pct = (missing / len(df) * 100).round(2)
    missing_df = pd.DataFrame({'Count': missing, 'Percentage': missing_pct})
    print(missing_df[missing_df['Count'] > 0] if missing.sum() > 0 else "No missing values")
    print(f"Total missing: {missing.sum()}")

    print(f"\n--- Duplicate Records ---")
    dupes = df.duplicated().sum()
    print(f"Duplicate rows: {dupes}")

    print(f"\n--- Unique Values ---")
    print(df.nunique())

    print(f"\n--- Descriptive Statistics (Numerical) ---")
    print(df.describe().round(2))

    print(f"\n--- Descriptive Statistics (Categorical) ---")
    print(df.describe(include='object'))


