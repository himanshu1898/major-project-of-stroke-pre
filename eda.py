# 5. Bivariate Analysis
# ============================================================
def _bivariate_analysis(df, output_dir):
    """Analyze relationships between stroke and key features."""
    print("\n--- Bivariate Analysis (Stroke vs Features) ---")

    # --- Numerical features vs stroke ---
    num_features = ['age', 'avg_glucose_level', 'bmi']

    fig, axes = plt.subplots(1, 3, figsize=(18, 5))
    colors = ['#4CAF50', '#F44336']

    for i, col in enumerate(num_features):
        for label, color in zip([0, 1], colors):
            subset = df[df['stroke'] == label][col].dropna()
            axes[i].hist(subset, bins=30, alpha=0.6, label=f'Stroke={label}',
                         color=color, edgecolor='black', linewidth=0.3)
        axes[i].set_title(f'{col} by Stroke Status', fontsize=12, fontweight='bold')
        axes[i].set_xlabel(col)
        axes[i].set_ylabel('Count')
        axes[i].legend()

        # Print mean comparison
        mean_0 = df[df['stroke'] == 0][col].mean()
        mean_1 = df[df['stroke'] == 1][col].mean()
        print(f"\n{col}: No-stroke mean={mean_0:.2f}, Stroke mean={mean_1:.2f}")

    plt.suptitle('Numerical Features by Stroke Status', fontsize=14, fontweight='bold', y=1.02)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '04_bivariate_numerical.png'), bbox_inches='tight')
    plt.close()

    # --- Box plots: numerical vs stroke ---
    fig, axes = plt.subplots(1, 3, figsize=(18, 5))

    for i, col in enumerate(num_features):
        data_0 = df[df['stroke'] == 0][col].dropna()
        data_1 = df[df['stroke'] == 1][col].dropna()
        bp = axes[i].boxplot([data_0, data_1], tick_labels=['No Stroke', 'Stroke'],
                              patch_artist=True)
        bp['boxes'][0].set_facecolor(colors[0])
        bp['boxes'][1].set_facecolor(colors[1])
        for box in bp['boxes']:
            box.set_alpha(0.7)
        axes[i].set_title(f'{col} by Stroke Status', fontsize=12, fontweight='bold')
        axes[i].set_ylabel(col)

    plt.suptitle('Box Plots: Numerical Features by Stroke', fontsize=14, fontweight='bold', y=1.02)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '05_bivariate_numerical_boxplots.png'), bbox_inches='tight')
    plt.close()

    # --- Categorical features vs stroke ---
    cat_features = ['gender', 'hypertension', 'heart_disease', 'ever_married',
                    'work_type', 'smoking_status']

    fig, axes = plt.subplots(2, 3, figsize=(20, 12))
    axes = axes.flatten()

    for i, col in enumerate(cat_features):
        # Calculate stroke rate per category
        stroke_rate = df.groupby(col)['stroke'].mean().sort_values(ascending=False)

        axes[i].bar(range(len(stroke_rate)), stroke_rate.values,
                    color='#FF9800', edgecolor='black', linewidth=0.5)
        axes[i].set_xticks(range(len(stroke_rate)))
        axes[i].set_xticklabels(stroke_rate.index, rotation=30, ha='right')
        axes[i].set_title(f'Stroke Rate by {col}', fontsize=12, fontweight='bold')
        axes[i].set_ylabel('Stroke Rate')
        axes[i].set_ylim(0, max(stroke_rate.values) * 1.3)

        # Add value labels
        for j, v in enumerate(stroke_rate.values):
            axes[i].text(j, v + 0.005, f'{v:.3f}', ha='center', fontsize=9)

        print(f"\n{col} stroke rates:")
        for val, rate in stroke_rate.items():
            print(f"  {val}: {rate:.4f}")

    plt.suptitle('Stroke Rate by Categorical Features', fontsize=15, fontweight='bold', y=1.01)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '06_bivariate_categorical.png'), bbox_inches='tight')
    plt.close()


