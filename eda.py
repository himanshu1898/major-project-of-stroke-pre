# 4. Categorical Feature Analysis
# ============================================================
def _categorical_analysis(df, output_dir):
    """Generate count plots for categorical features."""
    print("\n--- Categorical Feature Analysis ---")

    cat_features = ['gender', 'hypertension', 'heart_disease', 'ever_married',
                    'work_type', 'Residence_type', 'smoking_status']

    fig, axes = plt.subplots(3, 3, figsize=(20, 16))
    axes = axes.flatten()

    palette = sns.color_palette('Set2', 10)

    for i, col in enumerate(cat_features):
        counts = df[col].value_counts()
        axes[i].bar(range(len(counts)), counts.values, color=palette[:len(counts)],
                    edgecolor='black', linewidth=0.5)
        axes[i].set_xticks(range(len(counts)))
        axes[i].set_xticklabels(counts.index, rotation=30, ha='right')
        axes[i].set_title(f'{col}', fontsize=12, fontweight='bold')
        axes[i].set_ylabel('Count')

        # Add value labels
        for j, v in enumerate(counts.values):
            axes[i].text(j, v + 20, str(v), ha='center', fontsize=9)

        print(f"\n{col}:")
        for val, cnt in counts.items():
            print(f"  {val}: {cnt} ({cnt/len(df)*100:.1f}%)")

    # Hide unused subplots
    for j in range(len(cat_features), len(axes)):
        axes[j].set_visible(False)

    plt.suptitle('Categorical Feature Distributions', fontsize=15, fontweight='bold', y=1.01)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '03_categorical_distributions.png'), bbox_inches='tight')
    plt.close()


