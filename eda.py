# 3. Numerical Feature Analysis
# ============================================================
def _numerical_analysis(df, output_dir):
    """Generate histograms and box plots for numerical features."""
    print("\n--- Numerical Feature Analysis ---")

    num_features = ['age', 'avg_glucose_level', 'bmi']

    fig, axes = plt.subplots(2, 3, figsize=(18, 10))

    for i, col in enumerate(num_features):
        data = df[col].dropna()

        # Histogram + KDE
        axes[0, i].hist(data, bins=30, color='#2196F3', edgecolor='black',
                        alpha=0.7, density=True)
        data.plot(kind='kde', ax=axes[0, i], color='#F44336', linewidth=2)
        axes[0, i].set_title(f'{col} - Distribution', fontsize=12, fontweight='bold')
        axes[0, i].set_xlabel(col)
        axes[0, i].set_ylabel('Density')

        # Box plot
        bp = axes[1, i].boxplot(data, patch_artist=True, vert=True)
        bp['boxes'][0].set_facecolor('#4CAF50')
        bp['boxes'][0].set_alpha(0.7)
        axes[1, i].set_title(f'{col} - Box Plot', fontsize=12, fontweight='bold')
        axes[1, i].set_ylabel(col)

        # Print stats
        print(f"\n{col}:")
        print(f"  Mean:   {data.mean():.2f}")
        print(f"  Median: {data.median():.2f}")
        print(f"  Std:    {data.std():.2f}")
        print(f"  Min:    {data.min():.2f}")
        print(f"  Max:    {data.max():.2f}")
        print(f"  Skew:   {data.skew():.2f}")

    plt.suptitle('Numerical Feature Distributions', fontsize=15, fontweight='bold', y=1.02)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '02_numerical_distributions.png'), bbox_inches='tight')
    plt.close()


